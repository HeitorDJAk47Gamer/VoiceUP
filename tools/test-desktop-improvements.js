'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { createRecovery } = require('../update-recovery');
const quality = require('../public/viewer-quality');
const vm = require('node:vm');
const { EventEmitter } = require('node:events');
const features = fs.readFileSync(path.join(__dirname, '../public/beta-features.js'), 'utf8');
const binding = features.slice(features.indexOf('  const bindTransparentReconnect ='), features.indexOf('  const joinHostedRoomBeforeFeatures ='));
const states = [];
const current = new EventEmitter(); current.io = new EventEmitter();
const context = vm.createContext({ hostedSocket: current, setReconnectState: (...args) => states.push(args), reconnectBanner: { querySelector: () => ({ textContent: '' }) } });
vm.runInContext(binding + '\nglobalThis.bind = bindTransparentReconnect;', context);
context.bind(current);
current.emit('disconnect', 'transport close'); assert.deepEqual(states.at(-1), [true]);
current.emit('connect'); assert.deepEqual(states.at(-1), [true], 'TCP/socket connect must not claim room recovery');
current.emit('room-joined'); assert.deepEqual(states.at(-1), [false]);
current.__voiceupReconnectCancelled = true;
const count = states.length; current.io.emit('reconnect_attempt', 8); assert.equal(states.length, count);
current.__voiceupReconnectCancelled = false; context.hostedSocket = {};
current.emit('disconnect', 'transport close'); assert.equal(states.length, count, 'stale socket must not affect new session');
context.hostedSocket = current; current.__voiceupSessionReplaced = true;
current.io.emit('reconnect_error'); assert.equal(states.length, count);
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'voiceup-recovery-test-'));
try {
  const cache = createRecovery(directory);
  assert.equal(cache.read(), null);
  cache.save({ version: '1.2.3', phase: 'downloading' });
  assert.equal(createRecovery(directory).read().phase, 'downloading');
  cache.save({ version: '1.2.3', phase: 'installing' });
  assert.equal(cache.read().phase, 'installing');
  const digest = 'a'.repeat(64);
  assert.equal(cache.candidate({ assetName: '../../bad.exe', digest: `sha256:${digest}` }), path.join(directory, `${digest}.exe`));
  assert.throws(() => cache.candidate({ assetName: 'bad.exe', digest: '../escape' }));
  assert.throws(() => cache.candidate({ assetName: 'bad.cmd', digest: `sha256:${digest}` }));
  fs.writeFileSync(path.join(directory, 'pending.json'), '{');
  assert.equal(cache.read(), null);
  const limits = { height: 1080, fps: 60, bitrate: 12000000 };
  const low = quality.encoding({ height: 1080 }, limits, '360');
  assert.equal(low.scaleResolutionDownBy, 3);
  assert.equal(low.maxFramerate, 30);
  assert.equal(quality.encoding({ height: 360 }, { ...limits, height: 360, fps: 15 }, '1080').scaleResolutionDownBy, 1);
  assert.equal(quality.encoding({ height: 360 }, { ...limits, fps: 15 }, '1080').maxFramerate, 15);
  assert.equal(quality.encoding({ height: 2160 }, limits, 'auto').scaleResolutionDownBy, 2);
  for (const input of [null, {}, -1, '9999', '720<script>']) assert.equal(quality.normalize(input), null);
  const a = {}, b = {};
  quality.senders.set(a, '360'); quality.senders.set(b, 'auto');
  assert.equal(quality.senders.get(b), 'auto');
  console.log('PASS recovery journal, safe cache paths, viewer ceilings, independent settings and reconnect cancellation/stale-session guards');
} finally { fs.rmSync(directory, { recursive: true, force: true }); }
