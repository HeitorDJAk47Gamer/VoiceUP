'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const crypto = require('node:crypto');
const { io } = require('socket.io-client');
const { startSignalingServer } = require('../signaling-server');
const { MAX_FILE_BYTES } = require('../server-attachments');
const { createServerBackup, restoreServerBackup } = require('../server-backup');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'voiceup-files-'));
const sockets = []; let server, enabled = false, maxMB = 1;
const wait = (socket, event) => new Promise((resolve,reject) => { const timer = setTimeout(() => reject(Error(event)), 5000); socket.once(event, value => {clearTimeout(timer);resolve(value);}); });
const rpc = (socket, event, packet = {}) => new Promise((resolve,reject) => socket.timeout(5000).emit(event,packet,(error,result) => error ? reject(error) : resolve(result)));
(async () => {
  server = await startSignalingServer(0, { historyFile: path.join(directory,'chat-history.json'), attachmentsEnabled: () => enabled, attachmentMaxMB: () => maxMB, pluginDirectories: [] });
  const connect = async (room, name) => {
    const socket = io(`http://127.0.0.1:${server.server.address().port}`, { transports:['websocket'],reconnection:false }); sockets.push(socket);
    await wait(socket,'connect'); const joined = wait(socket,'room-joined'); socket.emit('join-room',{roomId:room,name,voiceChannel:'__lobby__',clientId:name}); await joined; return socket;
  };
  const alice = await connect('files','Alice'), bob = await connect('files','Bob'), other = await connect('other','Other');
  assert.equal((await rpc(alice,'attachment-policy')).policy.enabled,false);
  assert.equal((await rpc(alice,'attachment-begin',{name:'x',size:10,channel:'geral'})).ok,false);
  enabled = true;
  assert.equal((await rpc(alice,'attachment-begin',{name:'large',size:1048577,channel:'geral'})).ok,false);
  maxMB = 64;
  const hostLimit = await rpc(alice, 'attachment-policy');
  assert.equal(hostLimit.policy.maxBytes, 64 * 1024 * 1024);
  const overTwenty = await rpc(alice, 'attachment-begin', { name: 'host-limit.bin', size: 32 * 1024 * 1024, channel: 'geral' });
  assert.equal(overTwenty.ok, true, overTwenty.message);
  assert.equal((await rpc(alice, 'attachment-cancel')).ok, true);
  assert.equal(MAX_FILE_BYTES, 256 * 1024 * 1024);
  const content = crypto.randomBytes(90000), received = wait(bob,'text-message');
  const begin = await rpc(alice,'attachment-begin',{name:'../test.bin',size:content.length,channel:'geral'}); assert.equal(begin.ok,true);
  assert.equal((await rpc(alice,'attachment-chunk',{id:begin.id,offset:9,data:'YQ=='})).ok,false);
  assert.equal((await rpc(alice,'attachment-finish',{id:begin.id})).ok,false);
  for(let offset=0;offset<content.length;offset+=begin.chunkBytes) assert.equal((await rpc(alice,'attachment-chunk',{id:begin.id,offset,data:content.subarray(offset,offset+begin.chunkBytes).toString('base64')})).ok,true);
  const finish = await rpc(alice,'attachment-finish',{id:begin.id}); assert.equal(finish.ok,true,finish.message);
  assert.equal((await received).text,`[[voiceup-file:${begin.id}]]`);
  assert.equal((await rpc(other,'attachment-read',{id:begin.id})).ok,false);
  assert.equal((await rpc(bob,'attachment-read',{id:'../../server-settings'})).ok,false);
  const meta = await rpc(bob,'attachment-read',{id:begin.id}); assert.equal(meta.attachment.sha256,crypto.createHash('sha256').update(content).digest('hex'));
  const parts=[]; let offset=0;
  while(offset<content.length){const chunk=await rpc(bob,'attachment-read',{id:begin.id,offset}); assert.equal(chunk.ok,true); parts.push(Buffer.from(chunk.data,'base64'));offset=chunk.next;}
  assert.deepEqual(Buffer.concat(parts),content);
  const pending=await rpc(alice,'attachment-begin',{name:'x',size:3,channel:'geral'}); enabled=false;
  assert.equal((await rpc(alice,'attachment-chunk',{id:pending.id,offset:0,data:'YWJj'})).ok,false);
  assert.equal((await rpc(alice,'attachment-finish',{id:pending.id})).ok,false);
  fs.writeFileSync(path.join(directory,'server-settings.json'),'{}');
  const backup=path.join(directory,'files.voiceup-backup');
  createServerBackup({sourceDirectory:directory,destinationFile:backup,appVersion:'1.2.2-beta.27'});
  const restored=path.join(directory,'restored');
  restoreServerBackup({sourceFile:backup,destinationDirectory:restored});
  assert.deepEqual(fs.readFileSync(path.join(restored,'attachments',begin.id+'.bin')),content);
  assert.equal(JSON.parse(fs.readFileSync(path.join(restored,'attachments',begin.id+'.json'),'utf8')).channel,'geral');
  console.log('PASS attachments: disabled default, host maximum, malformed/partial blocks, permission revocation, channel isolation, exact binary roundtrip and backup inclusion');
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(async()=>{sockets.forEach(s=>s.disconnect());if(server){server.closeFederation?.();await new Promise(resolve=>server.io.close(resolve));server.server.close();}fs.rmSync(directory,{recursive:true,force:true});});
